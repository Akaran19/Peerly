// Browser translation (Safari/Chrome Translate) and some extensions move or
// replace text nodes that React manages. React then calls removeChild /
// insertBefore on nodes that are no longer children of the expected parent,
// which throws "NotFoundError" and crashes the whole tree. Make those calls
// tolerant so React can continue reconciling.
// See https://github.com/facebook/react/issues/11538
export function patchDomForExternalMutations() {
  if (typeof Node !== 'function' || !Node.prototype) return;

  const originalRemoveChild = Node.prototype.removeChild;
  Node.prototype.removeChild = function <T extends Node>(this: Node, child: T): T {
    if (child.parentNode !== this) {
      if (child.parentNode) {
        return originalRemoveChild.call(child.parentNode, child) as T;
      }
      return child;
    }
    return originalRemoveChild.call(this, child) as T;
  };

  const originalInsertBefore = Node.prototype.insertBefore;
  Node.prototype.insertBefore = function <T extends Node>(this: Node, newNode: T, referenceNode: Node | null): T {
    if (referenceNode && referenceNode.parentNode !== this) {
      return originalInsertBefore.call(this, newNode, null) as T;
    }
    return originalInsertBefore.call(this, newNode, referenceNode) as T;
  };
}
